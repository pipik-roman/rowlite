"""
Comprehensive Telemetry Engine for Rowlite Token Efficiency Benchmarks.
Captures multi-dimensional AI usage metrics:
  - Turn 1 Schema Tax vs Subsequent Context Expansion
  - Thinking / Reasoning Tokens (Cognitive Load)
  - Visible Output Tokens (Operational Conciseness)
  - Turn-by-Turn Context Accumulation & Latency
  - Integrity & Deterministic Mutation Verification
"""

from dataclasses import asdict, dataclass, field
import json
from typing import Any, Dict, List, Optional


@dataclass
class TurnRecord:
    turn_number: int
    prompt_tokens: int
    completion_tokens: int  # visible output tokens
    reasoning_tokens: int   # internal thinking tokens
    cached_tokens: int
    total_tokens: int
    tool_calls: List[str] = field(default_factory=list)
    tool_results_bytes: int = 0
    latency_ms: float = 0.0

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class RunTelemetry:
    condition: str
    num_rows: int
    turn1_prompt_tokens: int         # MCP Schema Tax
    subsequent_prompt_tokens: int   # Context accumulated after Turn 1
    total_prompt_tokens: int
    visible_completion_tokens: int  # Actual emitted tool calls & answers
    reasoning_tokens: int           # Thinking tokens generated by model
    total_completion_tokens: int    # visible_completion_tokens + reasoning_tokens
    cached_tokens: int
    total_tokens: int               # total_prompt + total_completion
    turns: int
    wall_clock_seconds: float
    verified: bool
    verification_message: str
    final_output: str
    turn_records: List[TurnRecord] = field(default_factory=list)

    @property
    def context_growth_tokens(self) -> int:
        """Prompt tokens accumulated beyond Turn 1 schema."""
        return max(0, self.total_prompt_tokens - self.turn1_prompt_tokens)

    @property
    def cognitive_ratio(self) -> float:
        """Ratio of thinking tokens to visible completion tokens."""
        if self.visible_completion_tokens == 0:
            return 0.0
        return self.reasoning_tokens / self.visible_completion_tokens

    def to_dict(self) -> Dict[str, Any]:
        data = asdict(self)
        data["context_growth_tokens"] = self.context_growth_tokens
        data["cognitive_ratio"] = round(self.cognitive_ratio, 2)
        return data


class UsageExtractor:
    """Safely extracts prompt, completion, cached, and reasoning tokens across providers."""

    @staticmethod
    def extract(usage_obj: Any) -> Dict[str, int]:
        if not usage_obj:
            return {
                "prompt_tokens": 0,
                "completion_tokens": 0,
                "reasoning_tokens": 0,
                "cached_tokens": 0,
                "total_tokens": 0,
            }

        # Check if dict
        if isinstance(usage_obj, dict):
            p = usage_obj.get("prompt_tokens", 0)
            c = usage_obj.get("completion_tokens", 0)
            t = usage_obj.get("total_tokens", p + c)
            r = 0
            if "completion_tokens_details" in usage_obj:
                cd = usage_obj["completion_tokens_details"]
                if isinstance(cd, dict):
                    r = cd.get("reasoning_tokens", 0)
            cached = 0
            if "prompt_tokens_details" in usage_obj:
                pd = usage_obj["prompt_tokens_details"]
                if isinstance(pd, dict):
                    cached = pd.get("cached_tokens", 0)
            return {
                "prompt_tokens": p,
                "completion_tokens": c,
                "reasoning_tokens": r,
                "cached_tokens": cached,
                "total_tokens": t,
            }

        # Attribute lookup (LiteLLM / Pydantic object)
        p = getattr(usage_obj, "prompt_tokens", 0) or 0
        c = getattr(usage_obj, "completion_tokens", 0) or 0
        t = getattr(usage_obj, "total_tokens", p + c) or (p + c)

        r = 0
        cd = getattr(usage_obj, "completion_tokens_details", None)
        if cd:
            r = getattr(cd, "reasoning_tokens", 0) or 0

        cached = 0
        pd = getattr(usage_obj, "prompt_tokens_details", None)
        if pd:
            cached = getattr(pd, "cached_tokens", 0) or 0

        return {
            "prompt_tokens": p,
            "completion_tokens": c,
            "reasoning_tokens": r,
            "cached_tokens": cached,
            "total_tokens": t,
        }


class SimulationThinkingModel:
    """
    Models realistic cognitive load (thinking tokens) in simulation mode.
    On raw filesystem tables, models must scan lines, verify pipe padding, and plan text mutations.
    On Rowlite MCP, models select declarative schema fields (where, set).
    """

    @staticmethod
    def estimate_reasoning_tokens(condition: str, turn: int, num_rows: int) -> int:
        if condition == "baseline_generic_file_tools":
            if turn == 1:
                # Deciding how to approach the task (tool choice: read_file)
                return 45
            elif turn == 2:
                # Mental parsing of entire table: identifying target row, planning column boundaries,
                # re-formatting pipe delimiters, ensuring other rows remain untouched.
                # Cognitive effort scales logarithmically with table size.
                base_effort = 120
                row_scaling = min(600, int(35 * (num_rows ** 0.45)))
                return base_effort + row_scaling
            elif turn == 3:
                # Final verification and confirmation formulation
                return 25
            return 30
        else:
            # Rowlite MCP condition
            if turn == 1:
                # Formulating declarative filter: matching 'where' and 'set' parameters
                return 55
            elif turn == 2:
                # Processing confirmation and formulating final answer
                return 20
            return 25
